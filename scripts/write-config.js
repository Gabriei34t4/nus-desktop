// Generates src/config.js from environment variables for a release build.
// The tracked config.js contains safe empty defaults; this script fills it
// with public-client integration configuration without committing credentials.
'use strict';

const fs = require('fs');
const path = require('path');

const REQUIRED = ['NUS_SUPABASE_URL', 'NUS_SUPABASE_ANON_KEY', 'NUS_GCAL_CLIENT_ID', 'NUS_GCAL_CLIENT_SECRET', 'NUS_OUTLOOK_CLIENT_ID'];
const target = path.join(__dirname, '..', 'src', 'config.js');
const allowEmpty = process.argv.includes('--allow-empty');

const missing = REQUIRED.filter((name) => !String(process.env[name] || '').trim());
if (missing.length && !allowEmpty) {
  console.error(`write-config: missing ${missing.join(', ')}. Set them as repository secrets or pass --allow-empty for a local-first build.`);
  process.exit(1);
}

const v = (name) => JSON.stringify(String(process.env[name] || '').trim());
const source = `// Runtime configuration for Nūs Desktop.
// Generated by scripts/write-config.js. Values are public client identifiers
// and public/anon keys only; never put service-role or private API keys here.
'use strict';

const config = {
  supabase: {
    url: process.env.NUS_SUPABASE_URL || ${v('NUS_SUPABASE_URL')},
    anonKey: process.env.NUS_SUPABASE_ANON_KEY || ${v('NUS_SUPABASE_ANON_KEY')},
  },
  googleCalendar: {
    clientId: process.env.NUS_GCAL_CLIENT_ID || ${v('NUS_GCAL_CLIENT_ID')},
    clientSecret: process.env.NUS_GCAL_CLIENT_SECRET || ${v('NUS_GCAL_CLIENT_SECRET')},
    scopes: ['https://www.googleapis.com/auth/calendar.events'],
  },
  outlook: {
    clientId: process.env.NUS_OUTLOOK_CLIENT_ID || ${v('NUS_OUTLOOK_CLIENT_ID')},
    tenant: 'common',
    scopes: ['User.Read', 'Mail.Read', 'offline_access'],
    sendScopes: ['User.Read', 'Mail.Read', 'Mail.Send', 'offline_access'],
  },
};

function isSupabaseConfigured(cfg = config) {
  return Boolean(cfg && cfg.supabase && cfg.supabase.url && cfg.supabase.anonKey);
}
function isGoogleCalendarConfigured(cfg = config) {
  return Boolean(cfg && cfg.googleCalendar && cfg.googleCalendar.clientId && cfg.googleCalendar.clientSecret);
}
function isOutlookConfigured(cfg = config) {
  return Boolean(cfg && cfg.outlook && cfg.outlook.clientId);
}
module.exports = { ...config, isSupabaseConfigured, isGoogleCalendarConfigured, isOutlookConfigured };
`;

fs.writeFileSync(target, source);
console.log(`write-config: generated src/config.js${missing.length ? ' (optional integrations disabled until configured)' : ''}`);
